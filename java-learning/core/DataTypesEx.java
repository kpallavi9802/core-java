public class DataTypesEx {
    public static void main(String[] args) {

        /*
         * Primitive Data Types
         * Integer --> short(2 byte) , byte (2 byte ), int (4 byte), long (8 byte) --> default is int
         * Float --> float ( 4 byte), double ( 8 byte ) --> default is double
         * Character --> support all characters worldwide ( unicode characters )
         * Boolean --> only accept true or false ( 0, 1 --> not acceptable) --> default is false
         * 
         * 1 byte --> 8 bits
         * Range Calculation --> 1 byte = -power(2, 8-1) to power(2, 8-1) -1
         */

        // Integer Data Type
        byte b = 127;
        short sh = 1234;
        int num = 12345;
        long l = 123456l;

        // Float Data Type
        float marks = 3.5f;
        double d = 3.5678;

        // Character Data Type
        char ch = 'k'; // only single quotes allowed\
        char ch1 = '8';



        // Boolean
        boolean bool = true;

    }
    
}
